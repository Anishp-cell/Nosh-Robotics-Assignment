#!/usr/bin/env python3
"""
CLI script: Create reproducible, leakage-aware 80:20 development/evaluation split.
"""

import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from eggcv.common.io import load_yaml
from eggcv.common.logging_utils import get_logger
from eggcv.dataset.create_split import SplitManager

logger = get_logger("create_split")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Partition dataset into reproducible 80:20 dev/eval splits with zero leakage.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--config",
        type=str,
        default=str(PROJECT_ROOT / "configs" / "dataset.yaml"),
        help="Path to dataset configuration YAML",
    )
    parser.add_argument(
        "--audit-csv",
        type=str,
        default=None,
        help="Path to dataset_audit.csv generated by audit_dataset.py",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Target path for split.csv (e.g. data/manifests/split.csv)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for deterministic split (overrides config split.random_seed)",
    )
    parser.add_argument(
        "--dev-ratio",
        type=float,
        default=None,
        help="Development split ratio (default: 0.80)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Force overwrite if split.csv already exists",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    cfg = load_yaml(args.config) if Path(args.config).is_file() else {}

    audit_path = args.audit_csv
    if not audit_path:
        audit_path = str(PROJECT_ROOT / cfg.get("manifests", {}).get("audit_file", "data/manifests/dataset_audit.csv"))

    audit_p = Path(audit_path).resolve()
    if not audit_p.is_file():
        logger.error(
            f"Audit manifest not found at: {audit_p}.\n"
            f"Please run the dataset audit first:\n"
            f"  python scripts/audit_dataset.py"
        )
        sys.exit(1)

    output_path = args.output
    if not output_path:
        output_path = str(PROJECT_ROOT / cfg.get("manifests", {}).get("split_file", "data/manifests/split.csv"))

    seed = args.seed if args.seed is not None else cfg.get("split", {}).get("random_seed", 42)
    dev_ratio = args.dev_ratio if args.dev_ratio is not None else cfg.get("split", {}).get("target_dev_ratio", 0.80)

    manager = SplitManager(random_seed=seed, target_dev_ratio=dev_ratio)

    try:
        split_df, summary = manager.create_split(
            audit_csv_path=audit_p,
            output_csv_path=output_path,
            force=args.force,
        )
    except FileExistsError as e:
        logger.error(f"{e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Failed to generate split: {e}")
        sys.exit(1)

    print("\n" + "=" * 65)
    print("DATASET SPLIT CREATED SUCCESSFULLY (ZERO LEAKAGE)")
    print("=" * 65)
    print(f"Random seed             : {summary['random_seed']}")
    print(f"Total eligible images   : {summary['total_images']}")
    print(f"Development set count   : {summary['actual_dev_count']} ({summary['actual_dev_ratio']*100:.1f}%)")
    print(f"Evaluation set count    : {summary['actual_eval_count']} ({summary['actual_eval_ratio']*100:.1f}%)")
    print(f"Unique duplicate groups : {summary['duplicate_groups_total']}")
    print("Folder distribution by split:")
    for folder, splits in summary["folder_distribution"].items():
        print(f"  {folder:20s}: dev={splits.get('development', 0)}, eval={splits.get('evaluation', 0)}")
    print("=" * 65 + "\n")


if __name__ == "__main__":
    main()
